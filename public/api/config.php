<?php
// Shared configuration and helpers for the THN API.

// ---- Session ----
if (session_status() == PHP_SESSION_NONE) {
    ini_set('session.cookie_httponly', 1);
    ini_set('session.use_only_cookies', 1);
    ini_set('session.cookie_samesite', 'Lax');
    if (isset($_SERVER['HTTPS']) && $_SERVER['HTTPS'] === 'on') {
        ini_set('session.cookie_secure', 1);
    }
    session_start();
}

// ---- CORS ----
// In production the site and API share one domain, so no CORS headers are needed.
// Cross-origin access is only allowed for the local Vite dev server.
$origin = isset($_SERVER['HTTP_ORIGIN']) ? $_SERVER['HTTP_ORIGIN'] : '';
if ($origin && preg_match('#^https?://(localhost|127\.0\.0\.1)(:\d+)?$#', $origin)) {
    header("Access-Control-Allow-Origin: " . $origin);
    header("Access-Control-Allow-Credentials: true");
    header("Access-Control-Allow-Headers: Content-Type, Authorization, X-Requested-With");
    header("Access-Control-Allow-Methods: GET, POST, OPTIONS");
    header("Vary: Origin");
}
header("Content-Type: application/json; charset=UTF-8");

if ($_SERVER['REQUEST_METHOD'] === 'OPTIONS') {
    http_response_code(200);
    exit();
}

// ---- Data files ----
// data.json / auth.json are live server data (edited from the Admin panel).
// They are NOT in git and are never overwritten by deploys. On a fresh server
// they are created once from the *.seed.json files that ship with each deploy.
define('DATA_FILE', __DIR__ . '/data.json');
define('DATA_SEED_FILE', __DIR__ . '/data.seed.json');
define('AUTH_FILE', __DIR__ . '/auth.json');
define('AUTH_SEED_FILE', __DIR__ . '/auth.seed.json');
define('MESSAGES_FILE', __DIR__ . '/messages.json');

if (!file_exists(DATA_FILE) && file_exists(DATA_SEED_FILE)) {
    copy(DATA_SEED_FILE, DATA_FILE);
}

// auth.seed.json is generated by the GitHub Actions deploy from the
// ADMIN_PASSWORD repository secret. There is deliberately no hard-coded default.
if (!file_exists(AUTH_FILE) && file_exists(AUTH_SEED_FILE)) {
    copy(AUTH_SEED_FILE, AUTH_FILE);
}

function isAdmin() {
    return isset($_SESSION['admin_logged_in']) && $_SESSION['admin_logged_in'] === true;
}

function requireAdmin() {
    if (!isAdmin()) {
        http_response_code(401);
        echo json_encode(["error" => "Unauthorized access. Admin login required."]);
        exit();
    }
}
?>
